// Trains a linear usage model on SYNTHETIC household data and writes the coefficients
// into supabase/functions/planner/assumptions.json. Results are not real-world accuracy.
// Run from the project root: node ml/train_synthetic.mjs
import { readFileSync, writeFileSync } from "node:fs";

const CONFIG = "supabase/functions/planner/assumptions.json";
const FEATURES = ["intercept", "home_size_100sqft", "people", "ac", "fan", "geyser", "pump", "summer", "ac_x_summer"];

let seed = 42;
const rand = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296;
  return seed / 4294967296;
};
const gauss = () => Math.sqrt(-2 * Math.log(rand() + 1e-12)) * Math.cos(2 * Math.PI * rand());
const randInt = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

function makeHousehold() {
  const sqft = randInt(400, 2500);
  const people = randInt(1, 6);
  const ac = randInt(0, Math.min(3, Math.floor(sqft / 500)));
  const fan = randInt(1, Math.max(2, Math.floor(sqft / 150)));
  const geyser = rand() < 0.7 ? 1 : 0;
  const pump = rand() < 0.4 ? 1 : 0;
  const summer = rand() < 0.4 ? 1 : 0;
  const kwh =
    40 + 0.12 * sqft + 35 * people + 220 * ac * (summer ? 1.5 : 0.6) + 40 * fan + 300 * geyser + 150 * pump +
    25 * gauss();
  return { x: [1, sqft / 100, people, ac, fan, geyser, pump, summer, ac * summer], y: Math.max(20, kwh) };
}

function solve(A, b) {
  const n = b.length;
  const M = A.map((row, i) => [...row, b[i]]);
  for (let col = 0; col < n; col++) {
    let pivot = col;
    for (let r = col + 1; r < n; r++) if (Math.abs(M[r][col]) > Math.abs(M[pivot][col])) pivot = r;
    [M[col], M[pivot]] = [M[pivot], M[col]];
    for (let r = 0; r < n; r++) {
      if (r === col) continue;
      const f = M[r][col] / M[col][col];
      for (let c = col; c <= n; c++) M[r][c] -= f * M[col][c];
    }
  }
  return M.map((row, i) => row[n] / row[i]);
}

function fit(rows) {
  const k = FEATURES.length;
  const XtX = Array.from({ length: k }, () => new Array(k).fill(0));
  const Xty = new Array(k).fill(0);
  for (const { x, y } of rows) {
    for (let i = 0; i < k; i++) {
      Xty[i] += x[i] * y;
      for (let j = 0; j < k; j++) XtX[i][j] += x[i] * x[j];
    }
  }
  return solve(XtX, Xty);
}

const predict = (beta, x) => beta.reduce((sum, b, i) => sum + b * x[i], 0);

const data = Array.from({ length: 5000 }, makeHousehold);
const split = Math.floor(data.length * 0.8);
const train = data.slice(0, split);
const test = data.slice(split);
const beta = fit(train);

const errors = test.map((r) => Math.abs(predict(beta, r.x) - r.y));
const mae = errors.reduce((a, b) => a + b, 0) / errors.length;
const meanY = test.reduce((a, r) => a + r.y, 0) / test.length;
const ssRes = test.reduce((a, r) => a + (r.y - predict(beta, r.x)) ** 2, 0);
const ssTot = test.reduce((a, r) => a + (r.y - meanY) ** 2, 0);
const r2 = 1 - ssRes / ssTot;

const coefficients = Object.fromEntries(FEATURES.map((f, i) => [f, Math.round(beta[i] * 1000) / 1000]));
const metrics = {
  data_source: "SYNTHETIC: generated by ml/train_synthetic.mjs, not real household data",
  model: "ordinary least squares, linear",
  train_rows: train.length,
  test_rows: test.length,
  mae_kwh_per_month: Math.round(mae * 10) / 10,
  r2: Math.round(r2 * 1000) / 1000,
};

const config = JSON.parse(readFileSync(CONFIG, "utf8"));
config.usage_model = {
  model_version: "synthetic-ols-v1",
  data_source: metrics.data_source,
  coefficients,
  metrics,
};
writeFileSync(CONFIG, JSON.stringify(config, null, 2) + "\n");
console.log(JSON.stringify(metrics, null, 2));
